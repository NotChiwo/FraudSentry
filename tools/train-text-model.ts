// Trains FraudSentry's text model and writes the evidence.
//   npm run train:text
// Writes:
//   src/text-model/trainedTextModel.json  the model the app uses (vocabulary, weights, bias)
//   src/text-model/trainingReport.json    the full report shown on the Detection Model page
//   docs/text-model/dataset.csv           every training / validation / test message with its label
//   docs/text-model/handwritten-test.csv  the hand-written messages never trained on, with the model's score
//   docs/text-model/training-log.csv      loss and validation accuracy after every epoch
//   docs/text-model/REPORT.md             the results, readable
import { writeFileSync } from 'node:fs';
import { trainTextModel, stratifiedSplit, TEXT_SEED, DATASET_SIZE, LABEL_NOISE, type EvalResult } from '../src/text-model/trainTextModel';
import { generateTextDataset } from '../src/text-model/textDataset';
import { HANDWRITTEN_TEST } from '../src/text-model/handwrittenTest';
import { scorer } from '../src/text-model/logisticRegression';
import { featureLabel } from '../src/text-model/textModel';
import { analyzeMessageText } from '../src/message-check/messageAnalysis';

const rules = (t: string) => analyzeMessageText(t, undefined, null, { textModel: false }).riskScore;
const t0 = Date.now();
const { model, report } = trainTextModel(rules);
const ms = Date.now() - t0;

writeFileSync('src/text-model/trainedTextModel.json', JSON.stringify(model) + '\n');
writeFileSync('src/text-model/trainingReport.json', JSON.stringify(report, null, 1) + '\n');

const data = generateTextDataset(DATASET_SIZE, TEXT_SEED, LABEL_NOISE);
const [train, val, test] = stratifiedSplit(data, [0.7, 0.15, 0.15], TEXT_SEED);
const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
const s = scorer(model);
writeFileSync('docs/text-model/dataset.csv', ['split,text,label,category,template', ...([['train', train], ['validation', val], ['test', test]] as const)
  .flatMap(([name, rows]) => rows.map(r => [name, q(r.text), r.label, q(r.category), r.template].join(',')))].join('\n') + '\n');
writeFileSync('docs/text-model/handwritten-test.csv', ['text,label,model_probability,model_says', ...HANDWRITTEN_TEST.map(r => {
  const p = s.probability(r.text); return [q(r.text), r.label, p.toFixed(4), p >= 0.5 ? 'scam' : 'legitimate'].join(',');
})].join('\n') + '\n');
writeFileSync('docs/text-model/training-log.csv', ['epoch,train_loss,validation_loss,validation_accuracy', ...report.history.map(h => [h.epoch, h.trainLoss, h.valLoss, h.valAccuracy].join(','))].join('\n') + '\n');

const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
const row = (name: string, e: EvalResult | null) => e ? `| ${name} | ${pct(e.accuracy)} | ${pct(e.precision)} | ${pct(e.recall)} | ${pct(e.f1)} | ${e.auc == null ? '–' : e.auc.toFixed(3)} | ${e.tp} / ${e.fp} / ${e.tn} / ${e.fn} |` : '';
const head = '| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | TP / FP / TN / FN |\n|---|---|---|---|---|---|---|';
const md = `# FraudSentry text model — training report

Generated by \`npm run train:text\` (tools/train-text-model.ts). Seed ${report.seed}; running it again gives exactly the same model and numbers (a test checks this).

## Data
- **Synthetic dataset:** ${report.dataset.size} Philippine SMS / chat messages (${report.dataset.scam} scam, ${report.dataset.legitimate} legitimate) generated from ${report.dataset.templates} templates in English, Tagalog and Taglish with random slots (bank / e-wallet, amount, link, phone, name, courier) and variations (case, "po", punctuation, typos). ${pct(report.dataset.labelNoise)} of labels flipped on purpose (real labels are never perfect). Every message: \`docs/text-model/dataset.csv\`.
- **Split (stratified):** ${report.split.train} training, ${report.split.validation} validation (watched during training), ${report.split.test} test (used once, at the end).
- **Hand-written test set:** ${report.split.handwritten} messages written separately from the templates and never trained on (\`docs/text-model/handwritten-test.csv\`).

| Category | Kind | Messages | Labels flipped (noise) |
|---|---|---|---|
${report.dataset.byCategory.map(c => `| ${c.category} | ${c.kind} | ${c.count} | ${c.flipped} |`).join('\n')}

## Model and training
Logistic regression on a binary bag of words and two-word phrases (${report.vocabularySize} features that appear in at least ${report.options.minCount} training messages). Links, phone numbers, amounts and codes are replaced by placeholders ([suspicious link], [phone number] …) so the model learns the kind of thing, not the exact value. Trained by mini-batch gradient descent: ${report.options.epochs} epochs, batch ${report.options.batchSize}, learning rate ${report.options.learningRate}/√epoch, L2 ${report.options.l2}. Training took ${(ms / 1000).toFixed(1)} s including the learning curve and cross-validation.

**Training curve** (log-loss; the untrained model, all weights 0, has loss ln 2 = 0.693):

| Epoch | Training loss | Validation loss | Validation accuracy |
|---|---|---|---|
${report.history.filter(h => [0, 1, 2, 3, 5, 10, 15, 20, 25, 30].includes(h.epoch)).map(h => `| ${h.epoch} | ${h.trainLoss.toFixed(4)} | ${h.valLoss.toFixed(4)} | ${pct(h.valAccuracy)} |`).join('\n')}

## Results
**Test set** (${report.split.test} messages, never seen in training):

${head}
${row('Untrained (all weights 0)', report.test.untrained)}
${row('Always the majority class', report.test.majority)}
${row('Rules only (the analyzer before the text model; flagged at Medium)', report.test.rulesOnly)}
${row('**Trained text model** (alone, 50 % threshold)', report.test.trained)}
${row('**Rules + text model** (what the app does)', report.test.combined)}

**Hand-written messages** (${report.split.handwritten}, not from the templates):

${head}
${row('Untrained', report.handwritten.untrained)}
${row('Rules only', report.handwritten.rulesOnly)}
${row('**Trained text model** (alone)', report.handwritten.trained)}
${row('**Rules + text model** (what the app does)', report.handwritten.combined)}

Hand-written messages the model got wrong:
${report.handwritten.mistakes.map(m => `- (${m.label ? 'scam' : 'legitimate'}, model ${pct(m.probability)} scam) ${m.text}`).join('\n')}

**Learning curve** (the same model trained on more of the training set, scored on the test set):

| Training messages | Test accuracy | Test F1 |
|---|---|---|
${report.learningCurve.map(l => `| ${l.trainSize} | ${pct(l.accuracy)} | ${pct(l.f1)} |`).join('\n')}

**5-fold cross-validation** (training + validation data): accuracy ${report.crossValidation.accuracy.map(pct).join(', ')}; mean ${pct(report.crossValidation.meanAccuracy)}. Mean F1 ${pct(report.crossValidation.meanF1)} ± ${pct(report.crossValidation.sdF1)}.

## What it learned
Words and phrases with the largest weights (positive → scam, negative → legitimate):

| Towards scam | Weight | Towards legitimate | Weight |
|---|---|---|---|
${report.topScam.map((t, i) => `| ${featureLabel(t.feature)} | +${t.weight.toFixed(3)} | ${featureLabel(report.topLegitimate[i].feature)} | ${report.topLegitimate[i].weight.toFixed(3)} |`).join('\n')}

## How the app uses it
The message checker keeps every rule-based finding and adds the model: final score = max(rules, 0.6 × rules + 0.4 × model probability). The model can raise a message the rules missed; it never lowers one the rules flagged.

## Limits
The training data is synthetic: it proves the method (the model is trained, learns sensible words, and generalises to messages written differently) but some learned weights reflect the templates (e.g. a courier or bank name that appears more often in one kind of template). Real collected and labelled messages are needed for field accuracy; \`npm run train:text\` retrains on whatever dataset \`textDataset.ts\` provides.
`;
writeFileSync('docs/text-model/REPORT.md', md);
console.log(`trained in ${ms} ms: ${report.vocabularySize} features; test accuracy ${pct(report.test.trained.accuracy)}, F1 ${pct(report.test.trained.f1)}; hand-written accuracy ${pct(report.handwritten.trained.accuracy)}`);
