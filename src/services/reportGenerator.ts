// Builds a professional, evidence-backed PDF from a REAL scan result.
// Every value printed comes from the stored analysis — nothing is
// invented at report time.
// ============================================================

import { jsPDF } from 'jspdf';
import { ImageScanResult, MessageScanResult } from '../types';
import { RISK_META, CLASSIFICATION_LABEL, classificationOf } from '../utils/helpers';
import type { FraudReport } from './fraudReports';

const NAVY = '#0f172a';
const BLUE = '#2563eb';
const MUTE = '#64748b';

function header(doc: jsPDF, title: string, caseId: string) {
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 26, 'F');
  doc.setTextColor('#ffffff'); doc.setFont('helvetica', 'bold'); doc.setFontSize(15);
  doc.text('FraudSentry', 14, 13);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor('#93c5fd');
  doc.text('Fraud Verification & Scam Intelligence Platform', 14, 19);
  doc.setFontSize(8); doc.setTextColor('#cbd5e1');
  doc.text(caseId, 196, 13, { align: 'right' });
  doc.text(new Date().toLocaleString('en-PH'), 196, 19, { align: 'right' });
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text(title, 14, 38);
  doc.setDrawColor(BLUE); doc.setLineWidth(0.6); doc.line(14, 41, 196, 41);
}

function riskBanner(doc: jsPDF, y: number, level: string, label: string, scorePct: number) {
  const m = RISK_META[level as keyof typeof RISK_META];
  const rgb = hexToRgb(m.hex);
  doc.setFillColor(rgb.r, rgb.g, rgb.b);
  doc.roundedRect(14, y, 182, 16, 2, 2, 'F');
  doc.setTextColor('#ffffff'); doc.setFont('helvetica', 'bold'); doc.setFontSize(11);
  doc.text(`${m.label.toUpperCase()}  ·  ${scorePct}%`, 18, y + 7);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  doc.text(label, 18, y + 12.5);
  return y + 22;
}

function hexToRgb(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

function sectionTitle(doc: jsPDF, y: number, text: string) {
  doc.setTextColor(BLUE); doc.setFont('helvetica', 'bold'); doc.setFontSize(10);
  doc.text(text, 14, y);
  return y + 5;
}

function kv(doc: jsPDF, y: number, k: string, v: string) {
  doc.setTextColor(MUTE); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  doc.text(k, 16, y);
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'bold');
  doc.text(v || '—', 70, y);
  return y + 5.5;
}

// jsPDF's built-in Helvetica only covers the WinAnsi character set: "₱" and the
// "•" used in masked names/numbers would print as garbage. Map them to ASCII.
function pdfSafe(t: string): string {
  return t.replace(/₱\s?/g, 'PHP ').replace(/[•●∙]/g, '*');
}

function footer(doc: jsPDF) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setDrawColor(220); doc.setLineWidth(0.3); doc.line(14, 285, 196, 285);
    doc.setTextColor(MUTE); doc.setFont('helvetica', 'normal'); doc.setFontSize(7);
    doc.text('Generated by FraudSentry — an evidence-based risk assessment, not a legal or bank-certified determination of fraud.', 14, 290);
    doc.text(`Page ${i} of ${pages}`, 196, 290, { align: 'right' });
  }
}

export function generateImageReport(scan: ImageScanResult) {
  const doc = new jsPDF();
  const caseId = `CASE-${scan.id.slice(-8).toUpperCase()}`;
  header(doc, 'Transaction Authenticity Report', caseId);
  let y = 48;
  y = riskBanner(doc, y, scan.riskLevel, scan.legitimacyLabel, Math.round(scan.riskScore * 100));

  // evidence preview
  if (scan.previewDataUrl) {
    try {
      const props = doc.getImageProperties(scan.previewDataUrl);
      const w = 52, h = Math.min(70, (props.height / props.width) * w);
      doc.addImage(scan.previewDataUrl, 'JPEG', 144, y, w, h);
    } catch { /* skip */ }
  }

  y = sectionTitle(doc, y, 'Evidence Source');
  y = kv(doc, y, 'File name', scan.filename);
  y = kv(doc, y, 'Detected institution', scan.source);
  y = kv(doc, y, 'Assessment confidence', `${scan.confidence}%`);
  y = kv(doc, y, 'Analyzed at', new Date(scan.scannedAt).toLocaleString('en-PH'));
  y += 3;

  y = sectionTitle(doc, y, 'Extracted Transaction Data (OCR)');
  const e = scan.extracted;
  y = kv(doc, y, 'Amount', e.amount != null ? `PHP ${e.amount.toLocaleString('en-PH', { minimumFractionDigits: 2 })}` : 'Not detected');
  y = kv(doc, y, 'Reference / Txn no.', e.referenceNo || e.transactionId || 'Not detected');
  y = kv(doc, y, 'Date / Time', [e.date, e.time].filter(Boolean).join(' ') || 'Not detected');
  y = kv(doc, y, 'Sender', pdfSafe(e.senderName || 'Not detected'));
  y = kv(doc, y, 'Receiver', pdfSafe(e.receiverName || 'Not detected'));
  y = kv(doc, y, 'Receiver No.', pdfSafe(e.receiverContact || 'Not detected'));
  y = kv(doc, y, 'OCR engine', `${scan.ocr.engine} · ${scan.ocr.confidence}% confidence`);
  y += 3;

  y = sectionTitle(doc, y, 'Image Forensics');
  const f = scan.forensics;
  y = kv(doc, y, 'Container (header)', f.sniffType);
  y = kv(doc, y, 'Dimensions', `${f.width}x${f.height} (${f.aspectRatio})`);
  y = kv(doc, y, 'EXIF metadata', f.hasExif ? 'present' : 'absent');
  y = kv(doc, y, 'Editor signature', f.editorSoftware || 'none');
  y = kv(doc, y, 'Error Level Analysis', `mean ${f.elaScore}/100, ${f.elaHotspotPct}% hotspots`);
  y += 4;

  // How the final score was formed — the Random Forest is half of it.
  if (scan.forestAnalysis) {
    const fa = scan.forestAnalysis;
    y = sectionTitle(doc, y, 'How the Risk Score Was Computed');
    y = kv(doc, y, 'Rule-based findings score', `${Math.round((scan.heuristicScore ?? 0) * 100)}%`);
    y = kv(doc, y, 'Random Forest probability', `${Math.round(fa.probability * 100)}% (${fa.votesFraud} of ${fa.totalTrees} trees voted fraudulent)`);
    y = kv(doc, y, 'Final risk (50% + 50%)', `${Math.round(scan.riskScore * 100)}%${scan.scoreFloor && scan.riskScore <= scan.scoreFloor + 1e-9 ? ' (minimum set by a definitive finding)' : ''}`);
    y = kv(doc, y, 'Classification', CLASSIFICATION_LABEL[scan.classification ?? classificationOf(scan.riskLevel)]);
    if (fa.modelName) y = kv(doc, y, 'Model', pdfSafe(fa.modelName));
    if (scan.txStatus) y = kv(doc, y, 'Payment outcome', scan.txStatus === 'received' ? 'money received (confirmed by the user)' : scan.txStatus === 'not-received' ? 'NOT received (confirmed by the user)' : 'not confirmed yet');
    y = kv(doc, y, 'Forest training data', fa.datasetSource === 'demo' ? 'seeded demonstration dataset (not real collected evidence)' : fa.datasetSource === 'labelled' ? 'your labelled scans (real evidence)' : 'uploaded labelled evidence dataset');
    y += 3;
  }

  y = sectionTitle(doc, y, 'Findings (weights within the rule-based score)');
  doc.setFontSize(8);
  for (const fd of scan.findings) {
    if (y > 268) { doc.addPage(); y = 20; }
    const rgb = hexToRgb(RISK_META[fd.severity].hex);
    doc.setFillColor(fd.passed ? 16 : rgb.r, fd.passed ? 185 : rgb.g, fd.passed ? 129 : rgb.b);
    doc.circle(16, y - 1.2, 1.1, 'F');
    doc.setTextColor(NAVY); doc.setFont('helvetica', 'bold');
    doc.text(`${fd.label}${fd.passed ? '' : `  (+${Math.round(fd.weight * 100)}% rule weight)`}`, 20, y);
    y += 4;
    doc.setTextColor(MUTE); doc.setFont('helvetica', 'normal');
    const lines = doc.splitTextToSize(pdfSafe(fd.detail), 174);
    doc.text(lines, 20, y); y += lines.length * 3.6 + 2;
  }

  if (y > 250) { doc.addPage(); y = 20; }
  y = sectionTitle(doc, y + 2, 'Recommended Action');
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  const rec = doc.splitTextToSize(scan.recommendedAction, 180);
  doc.text(rec, 16, y);
  y += rec.length * 4 + 3;

  if (scan.actionPlan && scan.actionPlan.length) {
    if (y > 250) { doc.addPage(); y = 20; }
    y = sectionTitle(doc, y, 'What To Do Next');
    doc.setFontSize(8.5);
    scan.actionPlan.forEach((step, i) => {
      const lines = doc.splitTextToSize(`${i + 1}. ${pdfSafe(step)}`, 178);
      if (y + lines.length * 4 > 280) { doc.addPage(); y = 20; }
      doc.text(lines, 16, y);
      y += lines.length * 4 + 1.5;
    });
  }

  footer(doc);
  doc.save(`${caseId}-transaction-report.pdf`);
}

export function generateMessageReport(scan: MessageScanResult) {
  const doc = new jsPDF();
  const caseId = `CASE-${scan.id.slice(-8).toUpperCase()}`;
  header(doc, 'Fraud Message Analysis Report', caseId);
  let y = 48;
  y = riskBanner(doc, y, scan.threatLevel, `${scan.scamType} · ${scan.platform}`, Math.round(scan.riskScore * 100));

  y = sectionTitle(doc, y, 'Summary');
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  const ex = doc.splitTextToSize(scan.explanation, 180); doc.text(ex, 16, y); y += ex.length * 4 + 4;

  y = sectionTitle(doc, y, 'Analyzed Message');
  doc.setFillColor(245, 247, 250); doc.setDrawColor(225);
  const msgLines = doc.splitTextToSize(pdfSafe(scan.sourceText.slice(0, 1200)), 176);
  const boxH = Math.min(60, msgLines.length * 3.8 + 6);
  doc.roundedRect(14, y, 182, boxH, 2, 2, 'FD');
  doc.setTextColor(MUTE); doc.setFontSize(7.6); doc.text(msgLines, 18, y + 5); y += boxH + 5;

  if (scan.flags.length) {
    y = sectionTitle(doc, y, 'Detected Fraud Signals');
    doc.setFontSize(8);
    for (const fl of scan.flags) {
      if (y > 268) { doc.addPage(); y = 20; }
      const rgb = hexToRgb(RISK_META[fl.severity].hex);
      doc.setFillColor(rgb.r, rgb.g, rgb.b); doc.circle(16, y - 1.2, 1.1, 'F');
      doc.setTextColor(NAVY); doc.setFont('helvetica', 'bold');
      doc.text(`"${pdfSafe(fl.keyword)}"  (+${Math.round(fl.weight * 100)}%)`, 20, y); y += 4;
      doc.setTextColor(MUTE); doc.setFont('helvetica', 'normal');
      const ls = doc.splitTextToSize(fl.reason, 174); doc.text(ls, 20, y); y += ls.length * 3.6 + 2;
    }
  }

  if (scan.links.length) {
    if (y > 250) { doc.addPage(); y = 20; }
    y = sectionTitle(doc, y + 2, 'Link Analysis');
    doc.setFontSize(8);
    for (const lk of scan.links) {
      if (y > 270) { doc.addPage(); y = 20; }
      doc.setTextColor(BLUE); doc.setFont('helvetica', 'bold'); doc.text(lk.url.slice(0, 80), 16, y); y += 4;
      doc.setTextColor(MUTE); doc.setFont('helvetica', 'normal');
      const ls = doc.splitTextToSize(lk.reason, 176); doc.text(ls, 16, y); y += ls.length * 3.6 + 2;
    }
  }

  if (y > 250) { doc.addPage(); y = 20; }
  y = sectionTitle(doc, y + 2, 'Recommended Actions');
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  for (const a of scan.recommendedActions) {
    const ls = doc.splitTextToSize('•  ' + a, 178); doc.text(ls, 16, y); y += ls.length * 4 + 1;
  }

  footer(doc);
  doc.save(`${caseId}-message-report.pdf`);
}

// ── period reports (REPORT table, V9.2) ──────────────────────
function table(doc: jsPDF, y: number, head: string[], rows: (string | number)[][], widths: number[]): number {
  const x0 = 14;
  const drawHead = () => {
    doc.setFillColor(241, 245, 249); doc.rect(x0, y - 4, 182, 6, 'F');
    doc.setTextColor(MUTE); doc.setFont('helvetica', 'bold'); doc.setFontSize(7.5);
    let x = x0 + 1.5; head.forEach((h, i) => { doc.text(h, x, y); x += widths[i]; });
    y += 5;
  };
  drawHead();
  doc.setFont('helvetica', 'normal'); doc.setTextColor(NAVY); doc.setFontSize(7.5);
  for (const r of rows) {
    if (y > 276) { doc.addPage(); y = 20; drawHead(); doc.setFont('helvetica', 'normal'); doc.setTextColor(NAVY); doc.setFontSize(7.5); }
    let x = x0 + 1.5;
    r.forEach((c, i) => { doc.text(doc.splitTextToSize(pdfSafe(String(c)), widths[i] - 2)[0] ?? '', x, y); x += widths[i]; });
    y += 4.6;
  }
  return y + 3;
}

const pctText = (v: number | null) => (v == null ? '-' : `${(v * 100).toFixed(1)}%`);

export function generateFraudReportPdf(r: FraudReport) {
  const doc = new jsPDF();
  const id = `REPORT-${r.id.replace(/[^a-z0-9]/gi, '').slice(-8).toUpperCase()}`;
  header(doc, `Fraud Detection Report (${r.reportType === 'summary' ? 'Summary' : 'Detailed'})`, id);
  let y = 48;
  y = kv(doc, y, 'Period', `${r.periodFrom} to ${r.periodTo}`);
  y = kv(doc, y, 'Scope', r.scope === 'all' ? 'all users of this device' : `records of ${r.username ?? 'this user'}`);
  y = kv(doc, y, 'Generated', `${new Date(r.generatedAt).toLocaleString('en-PH')}${r.username ? ` by ${r.username}` : ''}`);
  y += 2;
  y = sectionTitle(doc, y, 'Findings');
  doc.setTextColor(NAVY); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  const desc = doc.splitTextToSize(pdfSafe(r.description), 180);
  doc.text(desc, 16, y); y += desc.length * 4 + 4;

  const s = r.stats;
  y = sectionTitle(doc, y, 'Key figures');
  y = table(doc, y, ['Measure', 'Value'], [
    ['Checks', s.checks], ['Receipts / typed / messages / cross-evidence', `${s.byKind.Receipt} / ${s.byKind['Typed details']} / ${s.byKind.Message} / ${s.byKind['Cross-Evidence']}`],
    ['Possibly fraudulent', s.fraudulent], ['Legitimate', s.legitimate],
    ['Risk: low / medium / high / critical', `${s.byRisk.low} / ${s.byRisk.medium} / ${s.byRisk.high} / ${s.byRisk.critical}`],
    ['Outcome: pending / received / not received', `${s.outcomes.pending} / ${s.outcomes.received} / ${s.outcomes['not-received']}`],
    ['Claimed amount in flagged payments', `PHP ${s.amountFlagged.toLocaleString('en-PH', { minimumFractionDigits: 2 })}`],
    ['Alerts (unread)', `${s.alerts.total} (${s.alerts.unread})`],
  ], [120, 62]);

  y = sectionTitle(doc, y, 'Classification vs confirmed outcome');
  const a = s.agreement;
  y = table(doc, y, ['', 'Outcome: not received (fake)', 'Outcome: received (genuine)'], [
    ['Classified possibly fraudulent', `${a.tp} (caught)`, `${a.fp} (false alarm)`],
    ['Classified legitimate', `${a.fn} (missed)`, `${a.tn} (correct)`],
  ], [62, 60, 60]);
  y = kv(doc, y - 1, 'Confirmed payments', String(a.confirmed));
  y = kv(doc, y, 'Accuracy / precision / recall', `${pctText(a.accuracy)} / ${pctText(a.precision)} / ${pctText(a.recall)}`);
  y += 3;

  if (s.byApp.length) { if (y > 240) { doc.addPage(); y = 20; } y = sectionTitle(doc, y, 'By bank / e-wallet'); y = table(doc, y, ['App or bank', 'Checks', 'Possibly fraudulent', 'Not received'], s.byApp.map(x => [x.app, x.checks, x.fraudulent, x.notReceived]), [70, 30, 45, 37]); }
  if (s.byType.length) { if (y > 240) { doc.addPage(); y = 20; } y = sectionTitle(doc, y, 'By transaction type'); y = table(doc, y, ['Type', 'Checks', 'Possibly fraudulent'], s.byType.map(x => [x.type, x.checks, x.fraudulent]), [90, 40, 52]); }
  if (s.topReasons.length) { if (y > 240) { doc.addPage(); y = 20; } y = sectionTitle(doc, y, 'Most common warning signs'); y = table(doc, y, ['Check that failed', 'Times'], s.topReasons.map(x => [x.label, x.count]), [150, 32]); }
  if (s.models.length) { if (y > 240) { doc.addPage(); y = 20; } y = sectionTitle(doc, y, 'Models that scored the receipts'); y = table(doc, y, ['Model', 'Receipts'], s.models.map(x => [x.name, x.checks]), [150, 32]); }
  if (s.users?.length) { if (y > 240) { doc.addPage(); y = 20; } y = sectionTitle(doc, y, 'By user'); y = table(doc, y, ['User', 'Checks', 'Possibly fraudulent'], s.users.map(x => [x.username, x.checks, x.fraudulent]), [90, 40, 52]); }
  if (r.rows?.length) {
    if (y > 230) { doc.addPage(); y = 20; }
    y = sectionTitle(doc, y, `Every check (${r.rows.length})`);
    table(doc, y, ['When', 'Kind', 'App', 'Amount', 'Reference', 'Risk', 'Class', 'Outcome', ...(r.scope === 'all' ? ['User'] : [])],
      r.rows.map(x => [new Date(x.when).toLocaleDateString('en-PH'), x.kind, x.app, x.amount != null ? x.amount.toLocaleString('en-PH', { minimumFractionDigits: 2 }) : '-', x.reference ?? '-', x.riskLevel, x.classification === 'fraudulent' ? 'fraud?' : 'legit', x.outcome ?? '-', ...(r.scope === 'all' ? [x.user ?? ''] : [])]),
      r.scope === 'all' ? [20, 22, 20, 20, 32, 16, 14, 20, 18] : [22, 24, 22, 22, 36, 18, 16, 22]);
  }
  footer(doc);
  doc.save(`${id}-${r.reportType}-${r.periodFrom}-${r.periodTo}.pdf`);
}
