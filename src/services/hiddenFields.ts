// ============================================================
// FraudSentry — is a key detail deliberately hidden?
//
// Combines two independent signals:
//   1. Pixels: pixelated or covered areas found on the image
//      (obscuredRegions.ts), and whether one sits on the reference line.
//   2. Text: OCR read the "Ref No." label, but where the number should be it
//      read only junk ("Bf “Ew 9904 Bb") — what a mosaic, a scribble or a
//      blur over the digits turns into. This also catches covers the pixel
//      check can't see (e.g. a white box on a white card).
// A receipt is generated by the app: it never hides its own reference number.
// A hidden reference means the payment cannot be checked, so it must not be
// accepted as proof — even when the rest looks clean.
// ============================================================
import type { OcrWord } from '../types';
import type { ObscuredRegion } from './obscuredRegions';

export interface HiddenFields {
  regions: ObscuredRegion[];
  /** a pixelated/covered area overlaps the reference-number line */
  regionOnReference: boolean;
  /** a pixelated/covered area overlaps the line with the +63 mobile number */
  regionOnPhone: boolean;
  /** the reference label was read but its value is unreadable junk */
  referenceUnreadable: boolean;
  /** what the user is told */
  detail: string;
}

// "Ref No.", "Reference No.", "Reference ID", "Trace ID", "Transaction No."
// (+ OCR's "Rel No" / "Ref Mo")
const REF_LABEL = /\b(?:re[fl](?:erence)?\.?\s*(?:[nm]o\.?|number|#|id)|trace\s*id|transaction\s*(?:no\.?|number|id))\b/i;
// characters OCR produces from mosaic/scribble, never part of a reference
const JUNK = /[“”"‘’'®©|\[\]{}=~^\\<>§¶]/;
// where the value part of a "Ref No. …   Oct 04, 2026" line ends
const DATE_START = /\s{2,}(?=(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+\d|\d{1,2}[\/\-.]\d{1,2}[\/\-.]\d{2,4}|\d{1,2}\s+(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec))/i;

/** The text OCR read after the reference label, per pass. */
function referenceValues(texts: string[]): string[] {
  const out: string[] = [];
  for (const t of texts) for (const line of (t || '').split('\n')) {
    const m = line.match(REF_LABEL);
    if (!m || m.index === undefined) continue;
    const rest = line.slice(m.index + m[0].length).replace(/^[\s:.\-#]+/, '');
    out.push(rest.split(DATE_START)[0].trim());
  }
  return out;
}

/** Label read, value unreadable: the value is junk in most passes that saw the label. */
export function referenceLooksHidden(texts: string[], referenceNo: string | null): boolean {
  if (referenceNo) return false;
  const vals = referenceValues(texts);
  if (!vals.length) return false;
  const junk = vals.filter(v => v.length > 0 && (JUNK.test(v) || !/\d{6,}/.test(v.replace(/\s/g, '')) && /[a-z].*\d|\d.*[a-z]/i.test(v)));
  return junk.length >= Math.ceil(vals.length / 2);
}

/** The y-band of the reference line, from OCR word positions (pass 1). */
function referenceBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  if (!words?.length) return null;
  for (let i = 0; i < words.length; i++) {
    const w = words[i], next = words[i + 1];
    const pair = next ? `${w.text} ${next.text}` : w.text;
    if (REF_LABEL.test(pair) || /^re[fl](erence)?\.?$/i.test(w.text) && next && /^([nm]o\.?|number|id|#)$/i.test(next.text)) {
      const h = w.y1 - w.y0;
      return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
    }
  }
  return null;
}

/** The y-band of the line holding the "+63 …" mobile number. */
function phoneBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  const w = words?.find(x => /^\+?63/.test(x.text));
  if (!w) return null;
  const h = w.y1 - w.y0;
  return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
}

const onBand = (regions: ObscuredRegion[], band: { y0: number; y1: number; x: number } | null) =>
  !!band && regions.some(r => r.y < band.y1 && r.y + r.h > band.y0 && r.x + r.w > band.x);

export function assessHiddenFields(texts: string[], words: OcrWord[] | undefined, referenceNo: string | null, regions: ObscuredRegion[]): HiddenFields {
  const regionOnReference = onBand(regions, referenceBand(words));
  const regionOnPhone = onBand(regions, phoneBand(words));
  const referenceUnreadable = referenceLooksHidden(texts, referenceNo);
  const parts: string[] = [];
  if (regions.length) {
    const kinds = new Set(regions.map(r => r.kind));
    const what = kinds.has('pixelated') && kinds.has('covered') ? 'pixelated and covered' : kinds.has('pixelated') ? 'pixelated (blocked out with squares)' : 'covered with a solid box';
    const on = [regionOnReference ? 'the reference number' : '', regionOnPhone ? 'the mobile number' : ''].filter(Boolean).join(' and ');
    parts.push(`${regions.length === 1 ? 'Part of this receipt is' : `${regions.length} parts of this receipt are`} ${what}${on ? `, including ${on}` : ''}.`);
  }
  if (referenceUnreadable && !regionOnReference) parts.push('The "Ref No." label is visible, but the number after it cannot be read — it looks blocked out or scribbled over.');
  if (parts.length) parts.push('A bank or e-wallet app never hides details on its own receipt, so someone edited this image. Hidden details — above all the reference number — mean the payment cannot be checked. Do not accept this as proof of payment; ask for the full, unedited receipt and confirm the money in your own account.');
  return { regions, regionOnReference, regionOnPhone, referenceUnreadable, detail: parts.join(' ') };
}
