// ============================================================
// FraudSentry — is a key detail deliberately hidden?
//
// Combines two independent signals:
//   1. Pixels: pixelated or covered areas found on the image
//      (obscuredRegions.ts), and whether one sits on the reference line.
//   2. Text: OCR read the "Ref No." label, but where the number should be it
//      read only junk ("Bf “Ew 9904 Bb") — what a mosaic, a scribble or a
//      blur over the digits turns into. This also catches covers the pixel
//      check can't see (e.g. a white box on a white card).
// A receipt is generated by the app: it never hides its own reference number.
// A hidden reference, date or amount means the payment cannot be checked, so
// the receipt cannot be verified — even when the rest looks clean.
// Blurring only names or account numbers is common for privacy: when the
// reference, date and amount are all clearly readable, it is not held
// against the receipt.
// ============================================================
import type { ExtractedTransactionData, OcrWord } from '../../shared/types';
import type { ObscuredRegion } from './obscuredRegions';
import { locateFields } from '../reading/fieldLocator';

export interface HiddenFields {
  regions: ObscuredRegion[];
  /** a pixelated/covered area overlaps the reference-number line */
  regionOnReference: boolean;
  /** a pixelated/covered area overlaps the line with the +63 mobile number */
  regionOnPhone: boolean;
  /** the reference label was read but its value is unreadable junk */
  referenceUnreadable: boolean;
  /** key details a pixelated/covered area sits on (null: one of them could not be located, so it can't be ruled out) */
  keyDetailsCovered: ('reference' | 'date' | 'amount')[] | null;
  /** only other details (names, account numbers) are hidden; the reference, date and amount are readable */
  privacyOnly: boolean;
  /** a reference was read but is too short for its app, with junk or a blurred area where the rest should be ("1016 642 56▪▪") */
  referenceIncomplete: boolean;
  /** the "Total Amount Sent" label was read but its value is unreadable junk ("Total Amount Sent  £1 { a ma") */
  totalUnreadable: boolean;
  /** what the user is told */
  detail: string;
}

// "Ref No.", "Reference No.", "Reference ID", "Confirmation No." (BPI), "Trace ID", "Transaction No."
// (+ OCR's "Rel No" / "Ref Mo")
const REF_LABEL = /\b(?:re[fl](?:erence)?\.?\s*(?:[nm]o\.?|number|#|id)|confirmation\s*(?:[nm]o\.?|number|#|code)|trace\s*id|transaction\s*(?:no\.?|number|id))\b/i;
// characters OCR produces from mosaic/scribble, never part of a reference
const JUNK = /[“”"‘’'®©|\[\]{}=~^\\<>§¶]/;
// where the value part of a "Ref No. …   Oct 04, 2026" line ends
const DATE_START = /\s{2,}(?=(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+\d|\d{1,2}[\/\-.]\d{1,2}[\/\-.]\d{2,4}|\d{1,2}\s+(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec))/i;

/** The text OCR read after the reference label, per pass. */
function referenceValues(texts: string[]): string[] {
  const out: string[] = [];
  for (const t of texts) for (const line of (t || '').split('\n')) {
    const m = line.match(REF_LABEL);
    if (!m || m.index === undefined) continue;
    const rest = line.slice(m.index + m[0].length).replace(/^[\s:.\-#]+/, '');
    out.push(rest.split(DATE_START)[0].trim());
  }
  return out;
}

/** Label read, value unreadable: the value is junk in most passes that saw the label. */
export function referenceLooksHidden(texts: string[], referenceNo: string | null): boolean {
  if (referenceNo) return false;
  const vals = referenceValues(texts);
  if (!vals.length) return false;
  const junk = vals.filter(v => v.length > 0 && (JUNK.test(v) || !/\d{6,}/.test(v.replace(/\s/g, '')) && /[a-z].*\d|\d.*[a-z]/i.test(v)));
  return junk.length >= Math.ceil(vals.length / 2);
}

/** The y-band of the reference line, from OCR word positions (pass 1). */
function referenceBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  if (!words?.length) return null;
  for (let i = 0; i < words.length; i++) {
    const w = words[i], next = words[i + 1];
    const pair = next ? `${w.text} ${next.text}` : w.text;
    if (REF_LABEL.test(pair) || /^re[fl](erence)?\.?$/i.test(w.text) && next && /^([nm]o\.?|number|id|#)$/i.test(next.text)) {
      const h = w.y1 - w.y0;
      return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
    }
  }
  return null;
}

/** The y-band of the line holding the "+63 …" mobile number. */
function phoneBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  const w = words?.find(x => /^\+?63/.test(x.text));
  if (!w) return null;
  const h = w.y1 - w.y0;
  return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
}

const onBand = (regions: ObscuredRegion[], band: { y0: number; y1: number; x: number } | null) =>
  !!band && regions.some(r => r.y < band.y1 && r.y + r.h > band.y0 && r.x + r.w > band.x);

type KeyDetail = 'reference' | 'date' | 'amount';
const MONTH_WORD = /\b(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s*\d/i;

/**
 * Every printed line that holds a key detail, from the OCR word positions:
 * an amount line ("Amount", "Total Amount Sent", "Fee", "₱…", "1,000.00"), the
 * reference line, a date line. A receipt prints the amount more than once
 * ("Amount 150.00" and "Total Amount Sent ₱150.00"): blur on ANY of them hides it.
 */
function keyLines(words: OcrWord[]): { key: KeyDetail; y0: number; y1: number }[] {
  const lines: OcrWord[][] = [];
  for (const w of [...words].sort((a, b) => a.y0 - b.y0 || a.x0 - b.x0)) {
    const h = w.y1 - w.y0;
    const line = lines.find(l => Math.min(l[0].y1, w.y1) - Math.max(l[0].y0, w.y0) > Math.min(h, l[0].y1 - l[0].y0) * 0.5);
    if (line) line.push(w); else lines.push([w]);
  }
  const out: { key: KeyDetail; y0: number; y1: number }[] = [];
  for (const l of lines) {
    const text = l.map(w => w.text).join(' ');
    const y0 = Math.min(...l.map(w => w.y0)), y1 = Math.max(...l.map(w => w.y1));
    const add = (key: KeyDetail) => out.push({ key, y0, y1 });
    if (REF_LABEL.test(text)) add('reference');
    if (/\b(?:amount|total|fee)\b|₱|\bphp\b|\d[\d,]*\.\d{2}\b/i.test(text)) add('amount');
    if (MONTH_WORD.test(text) || /\b\d{1,2}[\/-]\d{1,2}[\/-]\d{2,4}\b/.test(text)) add('date');
  }
  return out;
}

/**
 * Which key details (reference, date, amount) a region sits on: any line that
 * prints one, plus where each read value was found. Null when nothing is
 * covered but a key detail was not read or not found, so it can't be ruled out.
 */
function keyDetailsUnder(regions: ObscuredRegion[], words: OcrWord[] | undefined, d: ExtractedTransactionData | undefined): HiddenFields['keyDetailsCovered'] {
  if (!d || !words?.length) return null;
  const out = new Set<KeyDetail>();
  const band = (y0: number, y1: number) => { const h = y1 - y0; return { y0: y0 - h * 0.6, y1: y1 + h * 0.6, x: 0 }; };
  for (const l of keyLines(words)) if (onBand(regions, band(l.y0, l.y1))) out.add(l.key);
  const boxes = locateFields(words, d);
  let unknown = false;
  for (const key of ['reference', 'date', 'amount'] as const) {
    const b = boxes.find(x => x.key === key);
    if (!b) { unknown = true; continue; }
    if (onBand(regions, band(b.y0, b.y1))) out.add(key);
  }
  if (out.size) return (['reference', 'date', 'amount'] as const).filter(k => out.has(k));
  if (!unknown) return [];
  // GCash and Maya print the reference and date BELOW the amounts: on a small
  // screenshot OCR may not place those lines, but a blurred area entirely above
  // the first amount line can only be the recipient's name or number.
  const firstAmount = keyLines(words).filter(l => l.key === 'amount').sort((a, b) => a.y0 - b.y0)[0];
  if (firstAmount && /^(?:GCash|Maya)$/.test(d.institution ?? '') && d.referenceNo && d.date
      && regions.every(r => r.y + r.h < firstAmount.y0)) return [];
  return null;
}

/** "Total Amount Sent" read, but no amount after it — only junk ("£1 { a ma", "1 [| a"), in most passes: blocked out. */
function totalLooksHidden(texts: string[]): boolean {
  const vals: string[] = [];
  for (const t of texts) for (const line of (t || '').split('\n')) {
    const m = line.match(/\btotal(?:\s+amount)?(?:\s+(?:sent|paid|transferred))?\b\s*[:.]?\s*(.*)$/i);
    if (m) vals.push(m[1].trim());
  }
  if (!vals.length) return false;
  const junk = vals.filter(v => v.length > 0 && !/\d[\d,]*\.\d{2}\b/.test(v) && (JUNK.test(v) || /[=~|\]\[{}]/.test(v) || /[a-z]/i.test(v)));
  return junk.length >= Math.ceil(vals.length / 2);
}

/** Junk after the reference digits on its line ("Ref No. 1016 642 56s =i"), in most passes: the rest is blocked out. */
function junkAfterReference(texts: string[]): boolean {
  const vals = referenceValues(texts);
  if (!vals.length) return false;
  const junk = vals.filter(v => {
    const rest = v.replace(/^[\d\s]+/, '').trim();
    return rest.length > 0 && (JUNK.test(rest) || /[=~|\]\[{}]/.test(rest) || /^[a-z]/i.test(rest));
  });
  return junk.length >= Math.ceil(vals.length / 2);
}

const KEY_NAME = { reference: 'the reference number', date: 'the date', amount: 'the amount' } as const;

/**
 * @param referenceShapeOk does the reference read have its app's known shape (GCash transfers: 13 digits)?
 *   false = too short or malformed; undefined = no known shape for this app.
 */
export function assessHiddenFields(texts: string[], words: OcrWord[] | undefined, referenceNo: string | null, regions: ObscuredRegion[], extracted?: ExtractedTransactionData, referenceShapeOk?: boolean): HiddenFields {
  const regionOnReference = onBand(regions, referenceBand(words));
  const regionOnPhone = onBand(regions, phoneBand(words));
  const referenceUnreadable = referenceLooksHidden(texts, referenceNo);
  // a short reference with the rest blurred or scribbled over: "1016 642 56▪▪" read as 101664256
  const referenceIncomplete = !!referenceNo && referenceShapeOk === false && (regions.length > 0 || junkAfterReference(texts));
  const totalUnreadable = totalLooksHidden(texts);
  const keyDetailsCovered = regions.length ? keyDetailsUnder(regions, words, extracted) : [];
  const privacyOnly = regions.length > 0 && !referenceUnreadable && !referenceIncomplete && !totalUnreadable && !regionOnReference && keyDetailsCovered?.length === 0;
  const parts: string[] = [];
  if (regions.length) {
    const kinds = new Set(regions.map(r => r.kind));
    const what = kinds.has('pixelated') && kinds.has('covered') ? 'blurred/pixelated and covered' : kinds.has('pixelated') ? 'blurred or pixelated' : 'covered with a solid box';
    const keys = new Set(keyDetailsCovered ?? []);
    if (regionOnReference) keys.add('reference');
    const on = [...[...keys].map(k => KEY_NAME[k]), regionOnPhone ? 'the mobile number' : ''].filter(Boolean);
    const list = on.length > 1 ? `${on.slice(0, -1).join(', ')} and ${on.at(-1)}` : on[0];
    parts.push(`${regions.length === 1 ? 'Part of this receipt is' : `${regions.length} parts of this receipt are`} ${what}${list ? `, including ${list}` : ''}.`);
  }
  if (referenceUnreadable && !regionOnReference) parts.push('The "Ref No." label is visible, but the number after it cannot be read — it looks blocked out or scribbled over.');
  if (totalUnreadable && !keyDetailsCovered?.includes('amount')) parts.push('The "Total Amount Sent" label is visible, but the amount after it cannot be read — it looks blocked out.');
  if (referenceIncomplete && !regionOnReference && !keyDetailsCovered?.includes('reference')) parts.push(`The reference number is cut short (only "${referenceNo}" can be read, too short for this app) and the rest of it looks blocked out.`);
  if (privacyOnly) parts.push('The reference number, date and amount are all clearly readable, so this looks like names or account numbers blurred for privacy. It does not count against the receipt.');
  else if (parts.length) parts.push('A bank or e-wallet app never blurs its own receipt, so this picture was changed after it was saved — sometimes only for privacy, but it means the payment cannot be checked from this screenshot. Ask for the original, unedited screenshot, and confirm the money in your own account.');
  return { regions, regionOnReference, regionOnPhone, referenceUnreadable, referenceIncomplete, totalUnreadable, keyDetailsCovered, privacyOnly, detail: parts.join(' ') };
}

// ── Values read THROUGH a blurred area ──
// OCR turns a mosaic into letters ("FRel fun Cruz A." from a pixelated name).
// A value whose words sit inside a blurred or covered area is noise, not the
// receipt's text: it is removed and shown as blurred.
export type ReadField = 'senderName' | 'receiverName' | 'receiverContact' | 'referenceNo' | 'transactionId' | 'amount' | 'date' | 'time';
const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
function tokenMatch(token: string, word: string): boolean {
  if (token === word) return true;
  // letters may differ by one OCR slip; numbers must match exactly
  if (/\d/.test(token) || token.length < 3 || Math.abs(token.length - word.length) > 1) return false;
  let i = 0, j = 0, slips = 0;
  while (i < token.length && j < word.length) {
    if (token[i] === word[j]) { i++; j++; continue; }
    if (++slips > 1) return false;
    if (token.length > word.length) i++; else if (word.length > token.length) j++; else { i++; j++; }
  }
  return slips + (token.length - i) + (word.length - j) <= 1;
}
/** Which read values lie inside a blurred / covered area (more of their words there than in clear text). */
export function fieldsUnderBlur(regions: ObscuredRegion[], words: OcrWord[] | undefined, d: ExtractedTransactionData): ReadField[] {
  if (!regions.length || !words?.length) return [];
  // a word is in the blur when its centre is (a blurred box is coarse and can graze the next line)
  const inside = (w: OcrWord) => {
    const m = (w.y1 - w.y0) * 0.25, cx = (w.x0 + w.x1) / 2, cy = (w.y0 + w.y1) / 2;
    return regions.some(r => cx > r.x - m && cx < r.x + r.w + m && cy > r.y - m && cy < r.y + r.h + m);
  };
  const covered = words.filter(inside).map(w => norm(w.text)).filter(Boolean);
  const clear = words.filter(w => !inside(w)).map(w => norm(w.text)).filter(Boolean);
  // Names and numbers of the parties are printed above the amounts on every layout
  // (GCash, Maya, BPI, MariBank …). Each OCR pass reads a mosaic as different
  // noise, so a name from another pass may match no word here: when a blur sits
  // in that party area and the name matches no CLEAR text either, it came from the blur.
  const firstAmount = keyLines(words).filter(l => l.key === 'amount').sort((a, b) => a.y0 - b.y0)[0];
  const blurInPartyArea = !!firstAmount && regions.some(r => r.y + r.h <= firstAmount.y0 + 2);
  const value: Record<ReadField, string | null> = {
    senderName: d.senderName, receiverName: d.receiverName, receiverContact: d.receiverContact, referenceNo: d.referenceNo,
    transactionId: d.transactionId, amount: d.amount == null ? null : d.amount.toFixed(2), date: d.date, time: d.time,
  };
  const out: ReadField[] = [];
  for (const [k, v] of Object.entries(value) as [ReadField, string | null][]) {
    if (!v) continue;
    const tokens = v.split(/[\s,]+/).map(norm).filter(t => t.length >= 2);
    if (!tokens.length) continue;
    const inBlur = tokens.filter(t => covered.some(w => tokenMatch(t, w))).length;
    const inClear = tokens.filter(t => clear.some(w => tokenMatch(t, w))).length;
    const party = k === 'receiverName' || k === 'senderName';   // a blurred phone is caught by its own check (regionOnPhone)
    if ((inBlur > 0 && inBlur >= tokens.length / 2 && inBlur >= inClear) || (party && blurInPartyArea && inClear === 0)) out.push(k);
  }
  return out;
}
