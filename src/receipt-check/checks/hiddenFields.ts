// ============================================================
// FraudSentry — is a key detail deliberately hidden?
//
// Combines two independent signals:
//   1. Pixels: pixelated or covered areas found on the image
//      (obscuredRegions.ts), and whether one sits on the reference line.
//   2. Text: OCR read the "Ref No." label, but where the number should be it
//      read only junk ("Bf “Ew 9904 Bb") — what a mosaic, a scribble or a
//      blur over the digits turns into. This also catches covers the pixel
//      check can't see (e.g. a white box on a white card).
// A receipt is generated by the app: it never hides its own reference number.
// A hidden reference, date or amount means the payment cannot be checked, so
// the receipt cannot be verified — even when the rest looks clean.
// Blurring only names or account numbers is common for privacy: when the
// reference, date and amount are all clearly readable, it is not held
// against the receipt.
// ============================================================
import type { ExtractedTransactionData, OcrWord } from '../../shared/types';
import type { ObscuredRegion } from './obscuredRegions';
import { locateFields } from '../reading/fieldLocator';

export interface HiddenFields {
  regions: ObscuredRegion[];
  /** a pixelated/covered area overlaps the reference-number line */
  regionOnReference: boolean;
  /** a pixelated/covered area overlaps the line with the +63 mobile number */
  regionOnPhone: boolean;
  /** the reference label was read but its value is unreadable junk */
  referenceUnreadable: boolean;
  /** key details a pixelated/covered area sits on (null: one of them could not be located, so it can't be ruled out) */
  keyDetailsCovered: ('reference' | 'date' | 'amount')[] | null;
  /** only other details (names, account numbers) are hidden; the reference, date and amount are readable */
  privacyOnly: boolean;
  /** what the user is told */
  detail: string;
}

// "Ref No.", "Reference No.", "Reference ID", "Confirmation No." (BPI), "Trace ID", "Transaction No."
// (+ OCR's "Rel No" / "Ref Mo")
const REF_LABEL = /\b(?:re[fl](?:erence)?\.?\s*(?:[nm]o\.?|number|#|id)|confirmation\s*(?:[nm]o\.?|number|#|code)|trace\s*id|transaction\s*(?:no\.?|number|id))\b/i;
// characters OCR produces from mosaic/scribble, never part of a reference
const JUNK = /[“”"‘’'®©|\[\]{}=~^\\<>§¶]/;
// where the value part of a "Ref No. …   Oct 04, 2026" line ends
const DATE_START = /\s{2,}(?=(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+\d|\d{1,2}[\/\-.]\d{1,2}[\/\-.]\d{2,4}|\d{1,2}\s+(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec))/i;

/** The text OCR read after the reference label, per pass. */
function referenceValues(texts: string[]): string[] {
  const out: string[] = [];
  for (const t of texts) for (const line of (t || '').split('\n')) {
    const m = line.match(REF_LABEL);
    if (!m || m.index === undefined) continue;
    const rest = line.slice(m.index + m[0].length).replace(/^[\s:.\-#]+/, '');
    out.push(rest.split(DATE_START)[0].trim());
  }
  return out;
}

/** Label read, value unreadable: the value is junk in most passes that saw the label. */
export function referenceLooksHidden(texts: string[], referenceNo: string | null): boolean {
  if (referenceNo) return false;
  const vals = referenceValues(texts);
  if (!vals.length) return false;
  const junk = vals.filter(v => v.length > 0 && (JUNK.test(v) || !/\d{6,}/.test(v.replace(/\s/g, '')) && /[a-z].*\d|\d.*[a-z]/i.test(v)));
  return junk.length >= Math.ceil(vals.length / 2);
}

/** The y-band of the reference line, from OCR word positions (pass 1). */
function referenceBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  if (!words?.length) return null;
  for (let i = 0; i < words.length; i++) {
    const w = words[i], next = words[i + 1];
    const pair = next ? `${w.text} ${next.text}` : w.text;
    if (REF_LABEL.test(pair) || /^re[fl](erence)?\.?$/i.test(w.text) && next && /^([nm]o\.?|number|id|#)$/i.test(next.text)) {
      const h = w.y1 - w.y0;
      return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
    }
  }
  return null;
}

/** The y-band of the line holding the "+63 …" mobile number. */
function phoneBand(words: OcrWord[] | undefined): { y0: number; y1: number; x: number } | null {
  const w = words?.find(x => /^\+?63/.test(x.text));
  if (!w) return null;
  const h = w.y1 - w.y0;
  return { y0: w.y0 - h * 0.6, y1: w.y1 + h * 0.6, x: w.x0 };
}

const onBand = (regions: ObscuredRegion[], band: { y0: number; y1: number; x: number } | null) =>
  !!band && regions.some(r => r.y < band.y1 && r.y + r.h > band.y0 && r.x + r.w > band.x);

/** Which of the reference, date and amount lines a region sits on; null if one of them was not read or not found on the image. */
function keyDetailsUnder(regions: ObscuredRegion[], words: OcrWord[] | undefined, d: ExtractedTransactionData | undefined): HiddenFields['keyDetailsCovered'] {
  if (!d || !words?.length) return null;
  const boxes = locateFields(words, d);
  const out: ('reference' | 'date' | 'amount')[] = [];
  for (const key of ['reference', 'date', 'amount'] as const) {
    const b = boxes.find(x => x.key === key);
    if (!b) return null;
    const h = b.y1 - b.y0;
    if (onBand(regions, { y0: b.y0 - h * 0.6, y1: b.y1 + h * 0.6, x: 0 })) out.push(key);
  }
  return out;
}

const KEY_NAME = { reference: 'the reference number', date: 'the date', amount: 'the amount' } as const;

export function assessHiddenFields(texts: string[], words: OcrWord[] | undefined, referenceNo: string | null, regions: ObscuredRegion[], extracted?: ExtractedTransactionData): HiddenFields {
  const regionOnReference = onBand(regions, referenceBand(words));
  const regionOnPhone = onBand(regions, phoneBand(words));
  const referenceUnreadable = referenceLooksHidden(texts, referenceNo);
  const keyDetailsCovered = regions.length ? keyDetailsUnder(regions, words, extracted) : [];
  const privacyOnly = regions.length > 0 && !referenceUnreadable && !regionOnReference && keyDetailsCovered?.length === 0;
  const parts: string[] = [];
  if (regions.length) {
    const kinds = new Set(regions.map(r => r.kind));
    const what = kinds.has('pixelated') && kinds.has('covered') ? 'blurred/pixelated and covered' : kinds.has('pixelated') ? 'blurred or pixelated' : 'covered with a solid box';
    const keys = new Set(keyDetailsCovered ?? []);
    if (regionOnReference) keys.add('reference');
    const on = [...[...keys].map(k => KEY_NAME[k]), regionOnPhone ? 'the mobile number' : ''].filter(Boolean);
    const list = on.length > 1 ? `${on.slice(0, -1).join(', ')} and ${on.at(-1)}` : on[0];
    parts.push(`${regions.length === 1 ? 'Part of this receipt is' : `${regions.length} parts of this receipt are`} ${what}${list ? `, including ${list}` : ''}.`);
  }
  if (referenceUnreadable && !regionOnReference) parts.push('The "Ref No." label is visible, but the number after it cannot be read — it looks blocked out or scribbled over.');
  if (privacyOnly) parts.push('The reference number, date and amount are all clearly readable, so this looks like names or account numbers blurred for privacy. It does not count against the receipt.');
  else if (parts.length) parts.push('A bank or e-wallet app never blurs its own receipt, so this picture was changed after it was saved — sometimes only for privacy, but it means the payment cannot be checked from this screenshot. Ask for the original, unedited screenshot, and confirm the money in your own account.');
  return { regions, regionOnReference, regionOnPhone, referenceUnreadable, keyDetailsCovered, privacyOnly, detail: parts.join(' ') };
}
